"""Build the demonstration set in data/samples/ from HELD-OUT TEST images (never used for training or tuning).

    python scripts/make_demo_set.py            # after scripts/download_datasets.py + prepare_datasets.py

Creates
    data/samples/steel_strip/<class>__<file>       2 per NEU-CLS class
    data/samples/bottle/<label>__<file>            2 per MVTec bottle label (good + 3 defect types)
    data/samples/metal_nut/<label>__<file>         2 per MVTec metal_nut label
    data/samples/unfamiliar/                       wrong-product inputs (expected: INCONCLUSIVE / review)
    data/samples/video/bottle_line.avi             a short clip for video inspection (good, defect, good)
    data/samples/README.md                         ground truth for every file

The images are not committed to git (dataset licences: MVTec AD CC BY-NC-SA 4.0, NEU-CLS academic use);
the folder is regenerated from the downloaded datasets.
"""
from __future__ import annotations

import json
import shutil
import sys
from collections import defaultdict
from pathlib import Path

import cv2

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "data" / "samples"
SETS = {"steel_strip": "neu_cls", "bottle": "mvtec_bottle", "metal_nut": "mvtec_metal_nut"}


def test_rows(dataset: str) -> list[dict]:
    m = json.loads((ROOT / "data" / "processed" / dataset / "manifest_latest.json").read_text())
    return [s for s in m["samples"] if s["split"] == "test"]


def main(per_label: int = 2):
    if OUT.exists():
        for p in OUT.iterdir():
            if p.name != ".gitkeep":
                shutil.rmtree(p) if p.is_dir() else p.unlink()
    OUT.mkdir(parents=True, exist_ok=True)
    readme = ["# Demonstration samples", "",
              "Generated by `python scripts/make_demo_set.py` from the **held-out test splits** (never used for",
              "training, threshold selection or model choice). Ground truth is part of each file name: `<label>__<file>`.",
              "", "| Folder | Use with profile | File | Ground truth | Expected behaviour |", "|---|---|---|---|---|"]
    for profile, ds in SETS.items():
        by = defaultdict(list)
        for r in test_rows(ds):
            by[r["label"]].append(r)
        d = OUT / profile
        d.mkdir()
        for label in sorted(by):
            for r in by[label][:per_label]:
                src = ROOT / r["path"]
                if not src.exists():
                    sys.exit(f"missing {src}: download the datasets first")
                dst = d / f"{label}__{src.name}"
                shutil.copy2(src, dst)
                exp = ("classified as this class" if profile == "steel_strip" else
                       "PASS (or REVIEW if borderline)" if label == "good" else "FAIL or REVIEW, defect outlined")
                readme.append(f"| {profile} | `{profile}` | {dst.name} | {label} | {exp} |")
    unf = OUT / "unfamiliar"
    unf.mkdir()
    b = ROOT / next(r for r in test_rows("mvtec_bottle") if r["label"] == "good")["path"]
    s = ROOT / next(r for r in test_rows("neu_cls") if r["label"] == "scratches")["path"]
    m = ROOT / next(r for r in test_rows("mvtec_metal_nut") if r["label"] == "good")["path"]
    for src, name, prof in ((b, "bottle_for_steel_profile.png", "steel_strip"),
                            (s, "steel_for_bottle_profile" + s.suffix, "bottle"),
                            (m, "metal_nut_for_bottle_profile.png", "bottle")):
        shutil.copy2(src, unf / name)
        readme.append(f"| unfamiliar | `{prof}` | {name} | wrong product | INCONCLUSIVE / unfamiliar input, manual review |")
    vid = OUT / "video"
    vid.mkdir()
    rows = test_rows("mvtec_bottle")
    frames = [ROOT / next(r for r in rows if r["label"] == lb)["path"] for lb in
              ("good", "good", "broken_large", "broken_large", "contamination", "good")]
    vw = cv2.VideoWriter(str(vid / "bottle_line.avi"), cv2.VideoWriter_fourcc(*"MJPG"), 1.0, (512, 512))
    for f in frames:
        vw.write(cv2.resize(cv2.imread(str(f)), (512, 512)))
    vw.release()
    readme.append("| video | `bottle` | bottle_line.avi | 1 fps: good, good, broken_large ×2, contamination, good | "
                  "sample every 1 s → 6 timestamped inspections + annotated video |")
    readme += ["", "Licences: MVTec AD — CC BY-NC-SA 4.0 (non-commercial); NEU-CLS — academic research use."]
    (OUT / "README.md").write_text("\n".join(readme) + "\n", encoding="utf-8")
    n = sum(1 for _ in OUT.rglob("*") if _.is_file())
    print(f"{n} files written to {OUT}")


if __name__ == "__main__":
    main()
